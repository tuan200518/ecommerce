-- Recommendation Service: read-model + "mô hình" gợi ý học dần từ luồng sự kiện.
-- SQL phải chạy được trên cả PostgreSQL và H2 (test).

-- Danh mục sản phẩm (read-model từ product-events)
CREATE TABLE IF NOT EXISTS rec_products (
    product_id    BIGINT PRIMARY KEY,
    name          VARCHAR(255)   NOT NULL,
    category_id   BIGINT,
    category_name VARCHAR(255),
    price         NUMERIC(18, 2),
    image_url     VARCHAR(1000),
    active        BOOLEAN        NOT NULL,
    updated_at    TIMESTAMP      NOT NULL
);

-- Thống kê dùng để chuẩn hóa độ tương đồng (cosine) và chất lượng (điểm đánh giá)
CREATE TABLE IF NOT EXISTS rec_product_stats (
    product_id   BIGINT PRIMARY KEY,
    buyers       BIGINT NOT NULL DEFAULT 0,
    viewers      BIGINT NOT NULL DEFAULT 0,
    rating_sum   BIGINT NOT NULL DEFAULT 0,
    rating_count BIGINT NOT NULL DEFAULT 0
);

-- Ma trận đồng xuất hiện item-item (collaborative filtering):
--   BOUGHT = cùng nằm trong một đơn đã thanh toán, VIEWED = cùng được một khách xem trong một phiên
CREATE TABLE IF NOT EXISTS rec_pairs (
    product_id BIGINT           NOT NULL,
    related_id BIGINT           NOT NULL,
    kind       VARCHAR(16)      NOT NULL,
    weight     DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (product_id, related_id, kind)
);

-- Độ phổ biến theo ngày (xu hướng có suy giảm theo thời gian)
CREATE TABLE IF NOT EXISTS rec_daily (
    product_id BIGINT NOT NULL,
    stat_day   DATE   NOT NULL,
    views      BIGINT NOT NULL DEFAULT 0,
    carts      BIGINT NOT NULL DEFAULT 0,
    purchases  BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (product_id, stat_day)
);

-- Hành vi của từng khách đã đăng nhập (hồ sơ sở thích)
CREATE TABLE IF NOT EXISTS rec_interactions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    product_id   BIGINT,
    category_id  BIGINT,
    kind         VARCHAR(16)  NOT NULL,
    search_query VARCHAR(255),
    occurred_at  TIMESTAMP    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_rec_interactions_user ON rec_interactions (user_id, occurred_at);

-- Hiệu quả từng vị trí gợi ý: lượt trả về, lượt hiển thị, lượt bấm, đơn hàng phát sinh
CREATE TABLE IF NOT EXISTS rec_placement_stats (
    stat_day    DATE             NOT NULL,
    placement   VARCHAR(32)      NOT NULL,
    requests    BIGINT           NOT NULL DEFAULT 0,
    impressions BIGINT           NOT NULL DEFAULT 0,
    clicks      BIGINT           NOT NULL DEFAULT 0,
    conversions BIGINT           NOT NULL DEFAULT 0,
    revenue     DOUBLE PRECISION NOT NULL DEFAULT 0,
    PRIMARY KEY (stat_day, placement)
);

-- Lượt bấm của khách đã đăng nhập → quy đơn hàng về gợi ý (attribution)
CREATE TABLE IF NOT EXISTS rec_clicks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    product_id BIGINT      NOT NULL,
    placement  VARCHAR(32) NOT NULL,
    clicked_at TIMESTAMP   NOT NULL,
    converted  BOOLEAN     NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_rec_clicks_user ON rec_clicks (user_id, product_id);

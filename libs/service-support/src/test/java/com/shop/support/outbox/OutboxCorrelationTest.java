package com.shop.support.outbox;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.datatype.jsr310.JavaTimeModule;
import com.shop.common.event.Correlation;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

class OutboxCorrelationTest {

    private final JdbcTemplate jdbc = new JdbcTemplate(new DriverManagerDataSource(
            "jdbc:h2:mem:outbox;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1", "sa", ""));
    private final ObjectMapper mapper = new ObjectMapper().registerModule(new JavaTimeModule());

    @AfterEach
    void clear() {
        Correlation.clear();
    }

    @Test
    void outboxRow_carriesCorrelationOfCurrentFlow() throws Exception {
        // Bảng kiểu cũ (không có correlation_id) → initializer tự bổ sung cột
        jdbc.execute("DROP TABLE IF EXISTS outbox_events");
        jdbc.execute("""
                CREATE TABLE outbox_events (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    event_id VARCHAR(64) NOT NULL UNIQUE, topic VARCHAR(128) NOT NULL, message_key VARCHAR(128),
                    event_type VARCHAR(128) NOT NULL, payload TEXT NOT NULL, created_at TIMESTAMP NOT NULL,
                    published_at TIMESTAMP NULL, attempts INT NOT NULL DEFAULT 0, last_error VARCHAR(1000))""");
        new SupportSchemaInitializer(jdbc).afterPropertiesSet();
        new SupportSchemaInitializer(jdbc).afterPropertiesSet(); // chạy lại không lỗi

        Correlation.set("trace-42");
        new OutboxService(jdbc, mapper, "test-service").publish("order-events", "OrderCreated", "1", Map.of("a", 1));

        Map<String, Object> row = jdbc.queryForMap("SELECT correlation_id, payload FROM outbox_events");
        assertThat(row.get("correlation_id")).isEqualTo("trace-42");
        assertThat(mapper.readTree((String) row.get("payload")).path("correlationId").asText()).isEqualTo("trace-42");
    }
}

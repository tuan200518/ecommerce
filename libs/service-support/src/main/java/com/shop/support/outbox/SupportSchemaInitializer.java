package com.shop.support.outbox;

import org.springframework.beans.factory.InitializingBean;
import org.springframework.jdbc.core.JdbcTemplate;

/**
 * Tạo bảng hạ tầng (outbox_events, processed_events) nếu chưa có.
 * Câu lệnh tương thích cả PostgreSQL và H2 (dùng trong test).
 */
public class SupportSchemaInitializer implements InitializingBean {

    private final JdbcTemplate jdbc;

    public SupportSchemaInitializer(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @Override
    public void afterPropertiesSet() {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS outbox_events (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    event_id VARCHAR(64) NOT NULL UNIQUE,
                    topic VARCHAR(128) NOT NULL,
                    message_key VARCHAR(128),
                    event_type VARCHAR(128) NOT NULL,
                    payload TEXT NOT NULL,
                    created_at TIMESTAMP NOT NULL,
                    published_at TIMESTAMP NULL,
                    attempts INT NOT NULL DEFAULT 0,
                    last_error VARCHAR(1000),
                    correlation_id VARCHAR(64)
                )""");
        // Bảng tạo từ phiên bản trước chưa có cột correlation_id
        jdbc.execute("ALTER TABLE outbox_events ADD COLUMN IF NOT EXISTS correlation_id VARCHAR(64)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_outbox_pending ON outbox_events (published_at, id)");
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS processed_events (
                    event_id VARCHAR(64) NOT NULL,
                    consumer VARCHAR(128) NOT NULL,
                    event_type VARCHAR(128),
                    processed_at TIMESTAMP NOT NULL,
                    PRIMARY KEY (event_id, consumer)
                )""");
    }
}
